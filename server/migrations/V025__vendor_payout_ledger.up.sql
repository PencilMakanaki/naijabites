CREATE TABLE vendor_payouts (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 public_id CHAR(26) NOT NULL,
 vendor_id BIGINT UNSIGNED NOT NULL,
 amount_kobo BIGINT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'NGN',
 status VARCHAR(24) NOT NULL DEFAULT 'requested',
 provider_reference VARCHAR(120) NULL,
 failure_reason VARCHAR(500) NULL,
 requested_by BIGINT UNSIGNED NOT NULL,
 processed_by BIGINT UNSIGNED NULL,
 requested_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 processed_at DATETIME(3) NULL,
 PRIMARY KEY(id), UNIQUE KEY uq_vendor_payouts_public_id(public_id),
 UNIQUE KEY uq_vendor_payouts_provider_reference(provider_reference),
 KEY ix_vendor_payouts_vendor_status(vendor_id,status,requested_at),
 CONSTRAINT fk_vendor_payouts_vendor FOREIGN KEY(vendor_id) REFERENCES vendors(id) ON DELETE RESTRICT,
 CONSTRAINT fk_vendor_payouts_requester FOREIGN KEY(requested_by) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_vendor_payouts_processor FOREIGN KEY(processed_by) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT ck_vendor_payouts_amount CHECK(amount_kobo > 0),
 CONSTRAINT ck_vendor_payouts_status CHECK(status IN ('requested','approved','processing','paid','failed','rejected'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE vendor_ledger_entries (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 vendor_id BIGINT UNSIGNED NOT NULL,
 vendor_order_id BIGINT UNSIGNED NULL,
 payout_id BIGINT UNSIGNED NULL,
 entry_type VARCHAR(24) NOT NULL,
 amount_kobo BIGINT NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'NGN',
 description VARCHAR(255) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY(id), KEY ix_vendor_ledger_vendor_created(vendor_id,created_at),
 CONSTRAINT fk_vendor_ledger_vendor FOREIGN KEY(vendor_id) REFERENCES vendors(id) ON DELETE RESTRICT,
 CONSTRAINT fk_vendor_ledger_order FOREIGN KEY(vendor_order_id) REFERENCES vendor_orders(id) ON DELETE RESTRICT,
 CONSTRAINT fk_vendor_ledger_payout FOREIGN KEY(payout_id) REFERENCES vendor_payouts(id) ON DELETE RESTRICT,
 CONSTRAINT ck_vendor_ledger_type CHECK(entry_type IN ('earning','commission','payout','adjustment','refund')),
 CONSTRAINT ck_vendor_ledger_nonzero CHECK(amount_kobo <> 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
