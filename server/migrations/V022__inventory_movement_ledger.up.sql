CREATE TABLE inventory_movements (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 public_id CHAR(26) NOT NULL,
 vendor_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 movement_type VARCHAR(24) NOT NULL,
 quantity_delta INT NOT NULL,
 quantity_before INT UNSIGNED NOT NULL,
 quantity_after INT UNSIGNED NOT NULL,
 reference_type VARCHAR(30) NULL,
 reference_id VARCHAR(64) NULL,
 note VARCHAR(500) NULL,
 actor_user_id BIGINT UNSIGNED NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY(id), UNIQUE KEY uq_inventory_movements_public_id(public_id),
 KEY ix_inventory_movements_branch_product(branch_id,product_id,created_at),
 KEY ix_inventory_movements_reference(reference_type,reference_id),
 CONSTRAINT fk_inventory_movements_inventory FOREIGN KEY(vendor_id,branch_id,product_id) REFERENCES branch_product_inventory(vendor_id,branch_id,product_id) ON DELETE RESTRICT,
 CONSTRAINT fk_inventory_movements_actor FOREIGN KEY(actor_user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT ck_inventory_movements_type CHECK(movement_type IN ('opening','restock','sale','release','adjustment','return','damage')),
 CONSTRAINT ck_inventory_movements_delta CHECK(quantity_delta <> 0),
 CONSTRAINT ck_inventory_movements_balance CHECK(quantity_after = quantity_before + quantity_delta)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
