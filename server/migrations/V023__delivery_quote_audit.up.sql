CREATE TABLE delivery_quote_events (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 public_id CHAR(26) NOT NULL,
 order_id BIGINT UNSIGNED NULL,
 user_id BIGINT UNSIGNED NULL,
 quote_source VARCHAR(30) NOT NULL,
 origin_latitude DECIMAL(10,7) NULL,
 origin_longitude DECIMAL(10,7) NULL,
 destination_latitude DECIMAL(10,7) NULL,
 destination_longitude DECIMAL(10,7) NULL,
 distance_meters INT UNSIGNED NULL,
 weight_grams BIGINT UNSIGNED NOT NULL DEFAULT 0,
 fee_kobo BIGINT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'NGN',
 outcome VARCHAR(20) NOT NULL DEFAULT 'quoted',
 failure_code VARCHAR(60) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY(id), UNIQUE KEY uq_delivery_quote_events_public_id(public_id),
 KEY ix_delivery_quote_events_order(order_id,created_at), KEY ix_delivery_quote_events_user(user_id,created_at),
 CONSTRAINT fk_delivery_quote_events_order FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE RESTRICT,
 CONSTRAINT fk_delivery_quote_events_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT ck_delivery_quote_events_source CHECK(quote_source IN ('flat_rate','google_routes','fallback')),
 CONSTRAINT ck_delivery_quote_events_outcome CHECK(outcome IN ('quoted','fallback','failed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
