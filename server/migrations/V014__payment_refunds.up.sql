CREATE TABLE payment_refunds (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id CHAR(26) NOT NULL,
  payment_id BIGINT UNSIGNED NOT NULL,
  order_id BIGINT UNSIGNED NOT NULL,
  requested_by BIGINT UNSIGNED NOT NULL,
  provider_refund_id BIGINT UNSIGNED NULL,
  amount_kobo BIGINT UNSIGNED NOT NULL,
  currency CHAR(3) NOT NULL DEFAULT 'NGN',
  reason VARCHAR(500) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT 'processing',
  provider_status VARCHAR(40) NULL,
  failure_reason VARCHAR(500) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  processed_at DATETIME(3) NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_payment_refunds_public_id (public_id),
  UNIQUE KEY uq_payment_refunds_payment (payment_id),
  UNIQUE KEY uq_payment_refunds_provider_id (provider_refund_id),
  KEY ix_payment_refunds_status_created (status, created_at),
  CONSTRAINT fk_payment_refunds_payment FOREIGN KEY (payment_id) REFERENCES payment_transactions(id) ON DELETE RESTRICT,
  CONSTRAINT fk_payment_refunds_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
  CONSTRAINT fk_payment_refunds_admin FOREIGN KEY (requested_by) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT chk_payment_refunds_amount CHECK (amount_kobo > 0),
  CONSTRAINT chk_payment_refunds_currency CHECK (currency = 'NGN'),
  CONSTRAINT chk_payment_refunds_status CHECK (status IN ('processing', 'processed', 'failed', 'needs_review'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
